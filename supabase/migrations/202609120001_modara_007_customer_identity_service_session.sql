create or replace function public.modara_normalize_customer_phone(input text)
returns text
language sql
immutable
set search_path = public
as $$
  select regexp_replace(coalesce(input, ''), '\D', '', 'g');
$$;

create or replace function public.modara_backfill_table_service_sessions()
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  table_session_row record;
  generated_service_session_id bigint;
  service_status text;
  service_closed_at timestamptz;
begin
  for table_session_row in
    select *
    from public.table_sessions
    where service_session_id is null
    order by id
  loop
    service_status :=
      case
        when table_session_row.status in ('closed', 'cancelled')
          then table_session_row.status
        else 'active'
      end;

    service_closed_at :=
      case
        when service_status in ('closed', 'cancelled')
          then coalesce(table_session_row.closed_at, table_session_row.updated_at, table_session_row.created_at, now())
        else null
      end;

    insert into public.service_sessions (
      unit_id,
      status,
      started_at,
      closed_at,
      created_at,
      updated_at
    )
    values (
      table_session_row.unit_id,
      service_status,
      coalesce(table_session_row.created_at, now()),
      service_closed_at,
      coalesce(table_session_row.created_at, now()),
      coalesce(table_session_row.updated_at, table_session_row.created_at, now())
    )
    returning id into generated_service_session_id;

    update public.table_sessions
    set service_session_id = generated_service_session_id
    where id = table_session_row.id;
  end loop;

  update public.customer_sessions customer_session
  set service_session_id = table_session_record.service_session_id
  from public.table_sessions table_session_record
  where customer_session.table_session_id = table_session_record.id
    and customer_session.service_session_id is null
    and table_session_record.service_session_id is not null;

  update public.orders order_record
  set service_session_id = table_session_record.service_session_id
  from public.table_sessions table_session_record
  where order_record.table_session_id = table_session_record.id
    and order_record.service_session_id is null
    and table_session_record.service_session_id is not null;
end;
$$;

select public.modara_backfill_table_service_sessions();

