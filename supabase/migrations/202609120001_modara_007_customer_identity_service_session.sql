create table if not exists public.service_sessions (
  id bigint generated by default as identity primary key,
  unit_id text not null check (btrim(unit_id) <> ''),
  customer_id bigint references public.customers(id) on delete restrict,
  status text not null default 'active',
  started_at timestamptz not null default now(),
  closed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint service_sessions_status_check
    check (status in ('active', 'closed', 'cancelled')),
  constraint service_sessions_closed_at_check
    check (
      (status = 'active' and closed_at is null)
      or (status in ('closed', 'cancelled') and closed_at is not null)
    )
);

