on public.orders
for each row execute function public.modara_guard_order_service_session();

create or replace function public.modara_start_service_session(
  target_unit_id text,
  target_preferred_name text,
  target_phone text,
  target_table_session_id bigint default null,
  target_existing_customer_id bigint default null
)
returns table (
  customer_id bigint,
  service_session_id bigint,
  customer_session_id bigint,
  preferred_name text,
  phone_normalized text,
  returning_customer boolean
)
language plpgsql
security definer
set search_path = public
as $$
declare
  normalized_phone text;
  normalized_name text;
  customer_record public.customers%rowtype;
  table_session_record public.table_sessions%rowtype;
  generated_service_session_id bigint;
begin
  normalized_name := btrim(coalesce(target_preferred_name, ''));
  normalized_phone := public.modara_normalize_customer_phone(target_phone);

  if btrim(coalesce(target_unit_id, '')) = '' then
    raise exception 'unit id is required';
  end if;

  if normalized_name = '' then
    raise exception 'preferred name is required';
  end if;

  if normalized_phone !~ '^[0-9]{10,15}$' then
    raise exception 'valid phone is required';
  end if;

  if target_existing_customer_id is not null then
    select *
    into customer_record
    from public.customers
    where public.customers.id = target_existing_customer_id
      and public.customers.unit_id = target_unit_id
      and public.customers.phone_normalized = normalized_phone;

    if not found then
      raise exception 'customer not found for unit and phone';
    end if;

    returning_customer := true;
  else
    returning_customer := exists (
      select 1
      from public.customers
      where public.customers.unit_id = target_unit_id
        and public.customers.phone_normalized = normalized_phone
    );

    insert into public.customers (
      unit_id,
      preferred_name,
      phone_normalized
    )
    values (
      target_unit_id,
      normalized_name,
      normalized_phone
    )
    on conflict on constraint customers_unit_id_phone_normalized_key
    do update set preferred_name = excluded.preferred_name
    returning * into customer_record;
  end if;

  if target_table_session_id is not null then
    select *
    into table_session_record
    from public.table_sessions
    where id = target_table_session_id
      and unit_id = target_unit_id
      and status = 'active'
    for update;

    if not found then
      raise exception 'active table session not found';
    end if;

    if table_session_record.service_session_id is null then
      insert into public.service_sessions (
        unit_id,
        customer_id,
        status
      )
      values (
        target_unit_id,
        customer_record.id,
        'active'
      )
      returning id into generated_service_session_id;

      update public.table_sessions
      set service_session_id = generated_service_session_id
      where id = table_session_record.id;
    else
      generated_service_session_id := table_session_record.service_session_id;
    end if;
  else
    insert into public.service_sessions (
      unit_id,
      customer_id,
      status
    )
    values (
      target_unit_id,
      customer_record.id,
      'active'
    )
    returning id into generated_service_session_id;
  end if;

  insert into public.customer_sessions (
    table_session_id,
    customer_id,
    service_session_id,
    name,
    display_name,
    phone
  )
  values (
    target_table_session_id,
    customer_record.id,
    generated_service_session_id,
    normalized_name,
    normalized_name,
    normalized_phone
  )
  returning id into customer_session_id;

  customer_id := customer_record.id;
  service_session_id := generated_service_session_id;
  preferred_name := customer_record.preferred_name;
  phone_normalized := customer_record.phone_normalized;

  return next;
end;
$$;

create or replace function public.modara_close_service_session_without_consumption(
  target_service_session_id bigint
)
returns public.service_sessions
language plpgsql
security definer
set search_path = public
as $$
declare
  session_record public.service_sessions%rowtype;
begin
  select *
  into session_record
  from public.service_sessions
  where id = target_service_session_id
  for update;

  if not found then
    raise exception 'service session not found';
  end if;

  if session_record.status = 'cancelled' then
    raise exception 'cancelled service session cannot be closed';
  end if;

  if session_record.status = 'closed' then
    return session_record;
  end if;

  if exists (
    select 1
    from public.orders
    where service_session_id = target_service_session_id
      and status <> 'cancelled'
  ) then
    raise exception 'service session has consumption';
  end if;

  update public.service_sessions
  set status = 'closed',
      closed_at = now()
  where id = target_service_session_id
  returning * into session_record;

  return session_record;
end;
$$;

