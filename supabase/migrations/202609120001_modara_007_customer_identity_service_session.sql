create or replace function public.modara_guard_customer_session_identity()
returns trigger
language plpgsql
set search_path = public
as $$
declare
  resolved_service_session_id bigint;
  service_customer_id bigint;
begin
  if tg_op = 'UPDATE' then
    if new.id is distinct from old.id
      or new.created_at is distinct from old.created_at then
      raise exception 'customer session structural fields are immutable';
    end if;
  end if;

  if new.table_session_id is not null then
    select service_session_id
    into resolved_service_session_id
    from public.table_sessions
    where id = new.table_session_id;

    if resolved_service_session_id is null then
      raise exception 'table session is missing service session';
    end if;

    if new.service_session_id is null then
      new.service_session_id := resolved_service_session_id;
    elsif new.service_session_id <> resolved_service_session_id then
      raise exception 'customer session service session does not match table session';
    end if;
  end if;

  if new.customer_id is not null and new.service_session_id is not null then
    select customer_id
    into service_customer_id
    from public.service_sessions
    where id = new.service_session_id;

    if service_customer_id is null then
      update public.service_sessions
      set customer_id = new.customer_id
      where id = new.service_session_id
        and customer_id is null;
    end if;
  end if;

  return new;
end;
$$;

drop trigger if exists customer_sessions_identity_guard
  on public.customer_sessions;
create trigger customer_sessions_identity_guard
before insert or update on public.customer_sessions
for each row execute function public.modara_guard_customer_session_identity();

create or replace function public.modara_guard_order_service_session()
returns trigger
language plpgsql
set search_path = public
as $$
declare
  table_service_session_id bigint;
  customer_service_session_id bigint;
  participant_status text;
begin
  if new.table_session_id is not null then
    select service_session_id
    into table_service_session_id
    from public.table_sessions
    where id = new.table_session_id;

    if table_service_session_id is null then
      raise exception 'table session is missing service session';
    end if;

    if new.service_session_id is null then
      new.service_session_id := table_service_session_id;
    elsif new.service_session_id <> table_service_session_id then
      raise exception 'order service session does not match table session';
    end if;
  end if;

  if new.customer_session_id is not null then
    select service_session_id, account_status
    into customer_service_session_id, participant_status
    from public.customer_sessions
    where id = new.customer_session_id;

    if customer_service_session_id is null then
      raise exception 'customer session is missing service session';
    end if;

    if new.service_session_id is null then
      new.service_session_id := customer_service_session_id;
    elsif new.service_session_id <> customer_service_session_id then
      raise exception 'order service session does not match customer session';
    end if;

    if participant_status in ('closed', 'legacy') then
      raise exception 'closed participant cannot create new consumption';
    end if;
  end if;

  return new;
end;
$$;

