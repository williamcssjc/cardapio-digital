create table if not exists public.fast_access_events (
  id bigint generated by default as identity primary key,
  unit_id text not null check (btrim(unit_id) <> ''),
  title text not null check (btrim(title) <> ''),
  starts_at timestamptz not null,
  ends_at timestamptz not null,
  uses_default_policy boolean not null default true,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (ends_at > starts_at)
);

create table if not exists public.fast_access_rules (
  id bigint generated by default as identity primary key,
  unit_id text not null check (btrim(unit_id) <> ''),
  event_id bigint references public.fast_access_events(id) on delete cascade,
  kind text not null check (kind in ('fallback', 'weekly', 'date', 'event')),
  weekday integer check (weekday between 1 and 7),
  effective_date date,
  starts_at time,
  ends_at time,
  timezone text not null default 'UTC' check (btrim(timezone) <> ''),
  access_status text not null check (
    access_status in ('free', 'pending', 'paid', 'waived')
  ),
  amount_cents bigint not null check (amount_cents >= 0),
  label text not null check (btrim(label) <> ''),
  priority integer not null default 0 check (priority >= 0),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (access_status <> 'free' or amount_cents = 0),
  check (
    (kind = 'fallback' and event_id is null and weekday is null and effective_date is null)
    or (kind = 'weekly' and event_id is null and weekday is not null and effective_date is null)
    or (kind = 'date' and event_id is null and weekday is null and effective_date is not null)
    or (kind = 'event' and event_id is not null)
  )
);

create table if not exists public.service_session_access (
  id bigint generated by default as identity primary key,
  service_session_id bigint not null references public.service_sessions(id) on delete cascade,
  customer_id bigint references public.customers(id) on delete restrict,
  unit_id text not null check (btrim(unit_id) <> ''),
  event_id bigint references public.fast_access_events(id) on delete restrict,
  access_rule_id bigint references public.fast_access_rules(id) on delete restrict,
  access_status text not null check (
    access_status in ('free', 'pending', 'paid', 'waived')
  ),
  source text not null check (
    source in ('fallback', 'weekly', 'date-override', 'event', 'manual')
  ),
  original_amount_cents bigint not null check (original_amount_cents >= 0),
  applied_amount_cents bigint not null check (applied_amount_cents >= 0),
  currency text not null default 'BRL' check (currency = 'BRL'),
  reason text not null check (btrim(reason) <> ''),
  resolved_at timestamptz not null default now(),
  confirmed_by uuid,
  confirmed_at timestamptz,
  snapshot jsonb not null default '{}'::jsonb,
  unique (service_session_id),
  check (access_status <> 'free' or applied_amount_cents = 0),
  check (
    (access_status in ('paid', 'waived') and confirmed_at is not null)
    or access_status in ('free', 'pending')
  )
);

create table if not exists public.fast_access_audit (
  id bigint generated by default as identity primary key,
  unit_id text not null check (btrim(unit_id) <> ''),
  actor_id uuid,
  action text not null check (btrim(action) <> ''),
  subject_type text not null check (btrim(subject_type) <> ''),
  subject_id bigint,
  previous_value jsonb,
  new_value jsonb,
  reason text,
  created_at timestamptz not null default now()
);

create index if not exists fast_access_events_unit_time_idx
  on public.fast_access_events(unit_id, active, starts_at, ends_at);
create index if not exists fast_access_rules_unit_lookup_idx
  on public.fast_access_rules(unit_id, active, kind, priority desc);
create index if not exists fast_access_rules_event_idx
  on public.fast_access_rules(event_id)
  where event_id is not null;
create index if not exists service_session_access_unit_status_idx
  on public.service_session_access(unit_id, access_status, resolved_at);
create index if not exists fast_access_audit_unit_created_idx
  on public.fast_access_audit(unit_id, created_at desc);

