create or replace function public.replace_table_account_item_allocations(
  target_account_item_id bigint,
  expected_allocation_version integer,
  requested_allocations jsonb
)
returns public.table_account_items
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  account_item public.table_account_items%rowtype;
  allocation jsonb;
  allocation_total bigint := 0;
  participant_id bigint;
  scope text;
  amount bigint;
begin
  perform set_config('modara.account_rpc', 'on', true);

  select * into account_item
  from public.table_account_items
  where id = target_account_item_id
  for update;

  if not found then
    raise exception 'Account item not found.';
  end if;

  if account_item.allocation_version <> expected_allocation_version then
    raise exception 'Account allocation changed concurrently.';
  end if;

  if jsonb_typeof(requested_allocations) <> 'array' then
    raise exception 'Allocations must be a JSON array.';
  end if;

  if exists (
    select 1 from public.table_account_settlements settlement
    where settlement.table_session_id = account_item.table_session_id
  ) then
    raise exception 'Settled account responsibilities cannot be redistributed in V1.';
  end if;

  if exists (
    select 1 from public.orders
    where id = account_item.order_id and status = 'cancelled'
  ) then
    raise exception 'Cancelled order items cannot be allocated.';
  end if;

  for allocation in select value from jsonb_array_elements(requested_allocations)
  loop
    scope := allocation->>'responsibilityScope';
    if scope not in ('participant', 'shared') then
      raise exception 'Invalid responsibility scope.';
    end if;

    if coalesce(allocation->>'amountCents', '') !~ '^\d+$' then
      raise exception 'Allocation amount must be an integer in cents.';
    end if;

    amount := (allocation->>'amountCents')::bigint;
    if amount <= 0 then
      raise exception 'Allocation amount must be positive.';
    end if;
    allocation_total := allocation_total + amount;

    if scope = 'participant' then
      if coalesce(allocation->>'customerSessionId', '') !~ '^\d+$' then
        raise exception 'Participant allocation requires a customer session.';
      end if;

      participant_id := (allocation->>'customerSessionId')::bigint;
      if not exists (
        select 1 from public.customer_sessions
        where id = participant_id
          and table_session_id = account_item.table_session_id
          and account_status = 'active'
      ) then
        raise exception 'Participant is not active in this table session.';
      end if;
    end if;
  end loop;

  if allocation_total <> account_item.total_cents then
    raise exception 'Allocations must match the immutable item total.';
  end if;

  delete from public.table_account_allocations
  where account_item_id = account_item.id;

  insert into public.table_account_allocations (
    account_item_id,
    table_session_id,
    customer_session_id,
    responsibility_scope,
    amount_cents,
    quantity,
    fraction_numerator,
    fraction_denominator
  )
  select
    account_item.id,
    account_item.table_session_id,
    case when value->>'responsibilityScope' = 'participant'
      then (value->>'customerSessionId')::bigint else null end,
    value->>'responsibilityScope',
    (value->>'amountCents')::bigint,
    case when coalesce(value->>'quantity', '') ~ '^\d+$'
      then (value->>'quantity')::integer else null end,
    case when coalesce(value->>'fractionNumerator', '') ~ '^\d+$'
      then (value->>'fractionNumerator')::integer else null end,
    case when coalesce(value->>'fractionDenominator', '') ~ '^\d+$'
      then (value->>'fractionDenominator')::integer else null end
  from jsonb_array_elements(requested_allocations);

  update public.table_account_items
  set allocation_version = allocation_version + 1,
      updated_at = now()
  where id = account_item.id
  returning * into account_item;

  return account_item;
end;
$$;

create or replace function public.settle_table_account_responsibility(
  target_table_session_id bigint,
  target_customer_session_id bigint,
  target_responsibility_scope text,
  settlement_idempotency_key text,
  settlement_created_by text default 'operation'
)
returns public.table_account_settlements
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  allocation_total bigint;
  settled_total bigint;
  open_amount bigint;
  settlement public.table_account_settlements%rowtype;
begin
  perform set_config('modara.account_rpc', 'on', true);

  if target_responsibility_scope not in ('participant', 'shared') then
    raise exception 'Invalid responsibility scope.';
  end if;

  if target_responsibility_scope = 'participant' then
    if target_customer_session_id is null then
      raise exception 'Participant settlement requires a customer session.';
    end if;

    perform 1
    from public.customer_sessions
    where id = target_customer_session_id
      and table_session_id = target_table_session_id
    for update;

    if not found then
      raise exception 'Participant does not belong to the table session.';
    end if;
  else
    target_customer_session_id := null;
  end if;

  select coalesce(sum(allocation.amount_cents), 0) into allocation_total
  from public.table_account_allocations allocation
  join public.table_account_items item on item.id = allocation.account_item_id
  join public.orders orders on orders.id = item.order_id
  where allocation.table_session_id = target_table_session_id
    and allocation.responsibility_scope = target_responsibility_scope
    and allocation.customer_session_id is not distinct from target_customer_session_id
    and orders.status <> 'cancelled';

  select coalesce(sum(amount_cents), 0) into settled_total
  from public.table_account_settlements
  where table_session_id = target_table_session_id
    and responsibility_scope = target_responsibility_scope
    and customer_session_id is not distinct from target_customer_session_id;

  open_amount := allocation_total - settled_total;

  if open_amount <= 0 then
    select * into settlement
    from public.table_account_settlements
    where table_session_id = target_table_session_id
      and idempotency_key = settlement_idempotency_key;

    if found then
      return settlement;
    end if;

    raise exception 'Responsibility has no open balance.';
  end if;

  insert into public.table_account_settlements (
    table_session_id,
    customer_session_id,
    responsibility_scope,
    amount_cents,
    idempotency_key,
    created_by
  ) values (
    target_table_session_id,
    target_customer_session_id,
    target_responsibility_scope,
    open_amount,
    settlement_idempotency_key,
    coalesce(nullif(btrim(settlement_created_by), ''), 'operation')
  )
  on conflict (table_session_id, idempotency_key) do nothing;

  select * into settlement
  from public.table_account_settlements
  where table_session_id = target_table_session_id
    and idempotency_key = settlement_idempotency_key;

  if settlement.amount_cents <> open_amount
    or settlement.responsibility_scope <> target_responsibility_scope
    or settlement.customer_session_id is distinct from target_customer_session_id then
    raise exception 'Idempotency key was reused for a different settlement.';
  end if;

  if target_responsibility_scope = 'participant' then
    update public.customer_sessions
    set account_status = 'closed',
        account_closed_at = coalesce(account_closed_at, now())
    where id = target_customer_session_id
      and table_session_id = target_table_session_id
      and account_status = 'active';
  end if;

  return settlement;
end;
$$;

create or replace function public.close_table_account_session(
  target_table_session_id bigint
)
returns public.table_sessions
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  table_session public.table_sessions%rowtype;
  open_amount bigint;
begin
  perform set_config('modara.account_rpc', 'on', true);

  select * into table_session
  from public.table_sessions
  where id = target_table_session_id
  for update;

  if not found then
    raise exception 'Table session not found.';
  end if;

  if table_session.status = 'cancelled' then
    raise exception 'Cancelled table sessions cannot be closed by account.';
  end if;

  open_amount := public.table_account_open_amount(target_table_session_id);
  if open_amount > 0 then
    raise exception 'Table session cannot close while account responsibility is open.';
  end if;

  if table_session.status = 'closed' then
    return table_session;
  end if;

  update public.table_sessions
  set status = 'closed',
      closed_at = coalesce(closed_at, now()),
      updated_at = now()
  where id = target_table_session_id
  returning * into table_session;

  return table_session;
end;
$$;

