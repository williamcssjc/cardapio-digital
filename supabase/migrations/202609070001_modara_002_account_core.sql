create or replace function public.materialize_order_account_items()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  item record;
  account_item_id bigint;
  participant_status text;
  unit_cents bigint;
  item_quantity integer;
begin
  if new.table_session_id is null then
    return new;
  end if;

  if new.customer_session_id is not null then
    select account_status into participant_status
    from public.customer_sessions
    where id = new.customer_session_id
      and table_session_id = new.table_session_id
    for update;

    if participant_status is null then
      raise exception 'Customer session does not belong to the order table session.';
    end if;
    if participant_status in ('closed', 'legacy') then
      raise exception 'Closed participant cannot create new consumption.';
    end if;
  end if;

  for item in
    select value, ordinality - 1 as item_index
    from jsonb_array_elements(coalesce(new.items::jsonb, '[]'::jsonb))
      with ordinality
  loop
    if jsonb_typeof(item.value) <> 'object'
      or coalesce(item.value->>'name', '') = ''
      or coalesce(item.value->>'price', '') !~ '^\d+(\.\d+)?$'
      or coalesce(item.value->>'qty', '') !~ '^\d+$' then
      raise exception 'Invalid order item snapshot for account materialization.';
    end if;

    unit_cents := round((item.value->>'price')::numeric * 100)::bigint;
    item_quantity := (item.value->>'qty')::integer;
    if item_quantity <= 0 then
      raise exception 'Order item quantity must be positive.';
    end if;

    insert into public.table_account_items (
      table_session_id,
      order_id,
      order_item_index,
      product_id,
      item_name,
      unit_price_cents,
      quantity,
      total_cents,
      source_customer_session_id
    ) values (
      new.table_session_id,
      new.id,
      item.item_index,
      case
        when coalesce(item.value->>'id', '') ~ '^\d+$'
          then (item.value->>'id')::bigint
        else null
      end,
      item.value->>'name',
      unit_cents,
      item_quantity,
      unit_cents * item_quantity,
      new.customer_session_id
    )
    returning id into account_item_id;

    if new.status <> 'cancelled' and new.customer_session_id is not null then
      insert into public.table_account_allocations (
        account_item_id,
        table_session_id,
        customer_session_id,
        responsibility_scope,
        amount_cents,
        quantity
      ) values (
        account_item_id,
        new.table_session_id,
        new.customer_session_id,
        'participant',
        unit_cents * item_quantity,
        item_quantity
      );
    elsif new.status <> 'cancelled' then
      insert into public.table_account_allocations (
        account_item_id,
        table_session_id,
        customer_session_id,
        responsibility_scope,
        amount_cents,
        quantity
      ) values (
        account_item_id,
        new.table_session_id,
        null,
        'shared',
        unit_cents * item_quantity,
        item_quantity
      );
    end if;
  end loop;

  return new;
end;
$$;

insert into public.table_account_items (
  table_session_id,
  order_id,
  order_item_index,
  product_id,
  item_name,
  unit_price_cents,
  quantity,
  total_cents,
  source_customer_session_id,
  created_at,
  updated_at
)
select
  orders.table_session_id,
  orders.id,
  item.ordinality - 1,
  case when coalesce(item.value->>'id', '') ~ '^\d+$'
    then (item.value->>'id')::bigint else null end,
  item.value->>'name',
  round((item.value->>'price')::numeric * 100)::bigint,
  (item.value->>'qty')::integer,
  round((item.value->>'price')::numeric * 100)::bigint
    * (item.value->>'qty')::integer,
  orders.customer_session_id,
  orders.created_at,
  orders.created_at
from public.orders orders
cross join lateral jsonb_array_elements(coalesce(orders.items::jsonb, '[]'::jsonb))
  with ordinality item(value, ordinality)
where orders.table_session_id is not null
  and jsonb_typeof(item.value) = 'object'
  and coalesce(item.value->>'name', '') <> ''
  and coalesce(item.value->>'price', '') ~ '^\d+(\.\d+)?$'
  and coalesce(item.value->>'qty', '') ~ '^\d+$'
  and (item.value->>'qty')::integer > 0;

insert into public.table_account_allocations (
  account_item_id,
  table_session_id,
  customer_session_id,
  responsibility_scope,
  amount_cents,
  quantity,
  created_at,
  updated_at
)
select
  account_item.id,
  account_item.table_session_id,
  account_item.source_customer_session_id,
  'participant',
  account_item.total_cents,
  account_item.quantity,
  account_item.created_at,
  account_item.updated_at
from public.table_account_items account_item
join public.orders orders on orders.id = account_item.order_id
join public.customer_sessions customer
  on customer.id = account_item.source_customer_session_id
  and customer.table_session_id = account_item.table_session_id
where orders.status <> 'cancelled'
  and customer.account_status = 'active';

insert into public.table_account_allocations (
  account_item_id,
  table_session_id,
  customer_session_id,
  responsibility_scope,
  amount_cents,
  quantity,
  created_at,
  updated_at
)
select
  account_item.id,
  account_item.table_session_id,
  null,
  'shared',
  account_item.total_cents,
  account_item.quantity,
  account_item.created_at,
  account_item.updated_at
from public.table_account_items account_item
join public.orders orders on orders.id = account_item.order_id
join public.table_sessions table_session on table_session.id = account_item.table_session_id
where orders.status <> 'cancelled'
  and orders.customer_session_id is null
  and table_session.status <> 'closed';

