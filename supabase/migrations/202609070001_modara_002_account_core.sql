alter table public.table_account_allocations replica identity full;
alter table public.table_account_settlements replica identity full;
alter table public.customer_sessions replica identity full;

do $$
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime') then
    alter publication supabase_realtime add table public.table_account_items;
    alter publication supabase_realtime add table public.table_account_allocations;
    alter publication supabase_realtime add table public.table_account_settlements;
    alter publication supabase_realtime add table public.customer_sessions;
  end if;
exception
  when duplicate_object then null;
end;
$$;

do $$
declare
  invalid_allocation_count integer;
  orphan_allocation_count integer;
  over_allocated_count integer;
  under_or_over_allocated_count integer;
  invalid_cancelled_count integer;
begin
  select count(*) into invalid_allocation_count
  from public.table_account_allocations
  where amount_cents <= 0;

  select count(*) into orphan_allocation_count
  from public.table_account_allocations allocation
  left join public.table_account_items item on item.id = allocation.account_item_id
  where item.id is null;

  select count(*) into over_allocated_count
  from (
    select item.id, item.total_cents, coalesce(sum(allocation.amount_cents), 0) as allocated_cents
    from public.table_account_items item
    left join public.table_account_allocations allocation on allocation.account_item_id = item.id
    group by item.id, item.total_cents
    having coalesce(sum(allocation.amount_cents), 0) > item.total_cents
  ) invalid_items;

  select count(*) into under_or_over_allocated_count
  from (
    select item.id, item.total_cents, coalesce(sum(allocation.amount_cents), 0) as allocated_cents
    from public.table_account_items item
    join public.orders orders on orders.id = item.order_id
    join public.table_sessions table_session on table_session.id = item.table_session_id
    left join public.table_account_allocations allocation on allocation.account_item_id = item.id
    where orders.status <> 'cancelled'
      and table_session.status <> 'closed'
    group by item.id, item.total_cents
    having coalesce(sum(allocation.amount_cents), 0) <> item.total_cents
  ) invalid_items;

  select count(*) into invalid_cancelled_count
  from public.table_account_allocations allocation
  join public.table_account_items item on item.id = allocation.account_item_id
  join public.orders orders on orders.id = item.order_id
  where orders.status = 'cancelled';

  if invalid_allocation_count <> 0
    or orphan_allocation_count <> 0
    or over_allocated_count <> 0
    or under_or_over_allocated_count <> 0
    or invalid_cancelled_count <> 0 then
    raise exception 'MODARA-002 account integrity validation failed.';
  end if;
end;
$$;

commit;
