create or replace function public.guard_customer_session_account_fields()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $$
begin
  if new.id is distinct from old.id
    or new.table_session_id is distinct from old.table_session_id
    or new.created_at is distinct from old.created_at then
    raise exception 'Customer session structural fields are immutable.';
  end if;

  if (new.account_status, new.account_closed_at)
    is distinct from (old.account_status, old.account_closed_at)
    and not public.modara_account_rpc_enabled() then
    raise exception 'Participant account state must be changed through account RPCs.';
  end if;

  if old.account_status in ('closed', 'legacy')
    and new.account_status is distinct from old.account_status then
    raise exception 'Closed participant account state is immutable in V1.';
  end if;

  if old.account_closed_at is not null
    and new.account_closed_at is distinct from old.account_closed_at then
    raise exception 'Participant account closed timestamp is immutable.';
  end if;

  return new;
end;
$$;

create trigger guard_customer_session_account_fields_trigger
before update on public.customer_sessions
for each row execute function public.guard_customer_session_account_fields();

create or replace function public.table_account_open_amount(target_table_session_id bigint)
returns bigint
language sql
stable
set search_path = public, pg_temp
as $$
  with active_allocations as (
    select coalesce(sum(allocation.amount_cents), 0)::bigint as amount_cents
    from public.table_account_allocations allocation
    join public.table_account_items item on item.id = allocation.account_item_id
    join public.orders orders on orders.id = item.order_id
    where allocation.table_session_id = target_table_session_id
      and orders.status <> 'cancelled'
  ),
  settled as (
    select coalesce(sum(amount_cents), 0)::bigint as amount_cents
    from public.table_account_settlements
    where table_session_id = target_table_session_id
  )
  select greatest(active_allocations.amount_cents - settled.amount_cents, 0)
  from active_allocations, settled;
$$;

create or replace function public.guard_table_account_close()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $$
begin
  if new.status = 'closed' and old.status is distinct from 'closed'
    and public.table_account_open_amount(new.id) > 0 then
    raise exception 'Table session cannot close while account responsibility is open.';
  end if;

  return new;
end;
$$;

create trigger guard_table_account_close_trigger
